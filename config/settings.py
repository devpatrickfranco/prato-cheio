def env_bool(nome, padrao=False):
    """Le uma variavel de ambiente booleana (1, true, yes, sim)."""
    valor = os.environ.get(nome)
    if valor is None:
        return padrao
    return valor.strip().lower() in ('1', 'true', 'yes', 'sim')


